// Tabs Navigation
function initTabs() {
  const buttons = document.querySelectorAll('.tab-btn');
  const panes = document.querySelectorAll('.tab-pane');
  
  buttons.forEach(btn => {
    btn.addEventListener('click', () => {
      buttons.forEach(b => b.classList.remove('active'));
      panes.forEach(p => p.classList.remove('active'));
      
      btn.classList.add('active');
      const target = document.getElementById(btn.dataset.tab);
      if (target) target.classList.add('active');
    });
  });

  // Check URL hash for direct tab navigation
  if (window.location.hash) {
    const hashTab = window.location.hash.replace('#', '');
    const matchingBtn = document.querySelector(`.tab-btn[data-tab="${hashTab}"]`);
    if (matchingBtn) matchingBtn.click();
  }
}

// Progress Calculator
function updateProgress() {
  const count = completedDays.length;
  const pct = Math.round((count / 21) * 100);
  
  const fill = document.getElementById('progressFill');
  const text = document.getElementById('progressText');
  const pctText = document.getElementById('progressPct');
  
  if (fill) fill.style.width = `${pct}%`;
  if (text) text.innerText = `${count} de 21 dias concluídos`;
  if (pctText) pctText.innerText = `${pct}%`;
}

// Toggle Day Completion
window.toggleDayCompleted = function(day) {
  if (completedDays.includes(day)) {
    completedDays = completedDays.filter(d => d !== day);
  } else {
    completedDays.push(day);
  }
  localStorage.setItem('cs_completed_days', JSON.stringify(completedDays));
  updateProgress();
  
  const card = document.getElementById(`dia-card-${day}`);
  if (card) {
    card.classList.toggle('completed', completedDays.includes(day));
  }
};

// Render Days
function renderDays(filterWeek) {
  const grid = document.getElementById('diasGrid');
  if (!grid) return;
  grid.innerHTML = '';

  JORNADA_DATA.dias.forEach(d => {
    const isW1 = d.dia <= 7;
    const isW2 = d.dia > 7 && d.dia <= 14;
    const isW3 = d.dia > 14;

    if (filterWeek === 'w1' && !isW1) return;
    if (filterWeek === 'w2' && !isW2) return;
    if (filterWeek === 'w3' && !isW3) return;

    const isDone = completedDays.includes(d.dia);
    
    let secretsHtml = '';
    d.segredos.forEach(s => {
      secretsHtml += `<span class="secret-tag">🌱 ${s.nome}</span>`;
    });

    const card = document.createElement('div');
    card.className = `dia-card ${isDone ? 'completed' : ''}`;
    card.id = `dia-card-${d.dia}`;
    card.innerHTML = `
      <div class="dia-header">
        <span class="dia-badge">Dia ${String(d.dia).padStart(2, '0')}</span>
        <span class="dia-week">${d.semana.split('·')[0] || 'Semana ' + (isW1 ? 1 : isW2 ? 2 : 3)}</span>
      </div>
      <div class="dia-secrets">
        ${secretsHtml || '<span class="secret-tag">Rotina e Dicas</span>'}
      </div>
      <label class="check-label">
        <input type="checkbox" ${isDone ? 'checked' : ''} onchange="toggleDayCompleted(${d.dia})">
        Concluído hoje
      </label>
      <div class="dia-actions">
        <button class="btn-open" onclick="openReader('${d.arquivo}', 'Dia ${d.dia}')">Abrir Dia</button>
        <button class="btn-premium" onclick="openReader('${d.arquivo_premium}', 'Dia ${d.dia} Premium')">★ Premium</button>
      </div>
    `;
    grid.appendChild(card);
  });
}

// Filter Week Pill Buttons
window.filterDays = function(week, btn) {
  document.querySelectorAll('.pill-filter').forEach(p => p.classList.remove('active'));
  btn.classList.add('active');
  renderDays(week);
};

// Shopping List Logic
function renderShoppingList() {
  const container = document.getElementById('shoppingListContainer');
  if (!container) return;
  container.innerHTML = '';

  let totalItems = 0;
  let totalChecked = 0;

  SHOPPING_DATA.forEach(cat => {
    const sec = document.createElement('div');
    sec.className = 'shopping-section';
    
    let itemsHtml = '';
    cat.itens.forEach(item => {
      totalItems++;
      const isChecked = checkedItems.includes(item.id);
      if (isChecked) totalChecked++;

      itemsHtml += `
        <div class="shop-item ${isChecked ? 'checked' : ''}" id="shop-${item.id}" onclick="toggleShopItem('${item.id}')">
          <input type="checkbox" ${isChecked ? 'checked' : ''} onclick="event.stopPropagation(); toggleShopItem('${item.id}')">
          <div class="shop-item-info">
            <div class="shop-item-name">${item.nome}</div>
            <div class="shop-item-desc">${item.desc}</div>
          </div>
        </div>
      `;
    });

    sec.innerHTML = `
      <h3>${cat.categoria}</h3>
      <div class="shop-items">${itemsHtml}</div>
    `;
    container.appendChild(sec);
  });

  updateShoppingStats(totalChecked, totalItems);
}

function updateShoppingStats(checked, total) {
  const stat = document.getElementById('shoppingCounter');
  if (stat) stat.innerText = `${checked} de ${total} comprados`;
}

window.toggleShopItem = function(id) {
  if (checkedItems.includes(id)) {
    checkedItems = checkedItems.filter(i => i !== id);
  } else {
    checkedItems.push(id);
  }
  localStorage.setItem('cs_checked_items', JSON.stringify(checkedItems));
  renderShoppingList();
};

window.clearShopping = function() {
  if (confirm("Deseja desmarcar todos os itens da lista de compras?")) {
    checkedItems = [];
    localStorage.setItem('cs_checked_items', JSON.stringify(checkedItems));
    renderShoppingList();
  }
};

